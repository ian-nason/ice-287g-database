args <- commandArgs(TRUE)
if(length(args)>=3 && nzchar(args[[3]])) .libPaths(c(args[[3]],.libPaths()))
library(datapond)
library(DBI)
options(datapond.registry_url=args[[1]],datapond.cache_dir=args[[2]])
probe<-dbConnect(duckdb::duckdb())
stopifnot(dbGetQuery(probe,"SELECT installed FROM duckdb_extensions() WHERE extension_name='httpfs'")$installed[[1]])
dbDisconnect(probe,shutdown=TRUE)
stopifnot(identical(dp_list(),'ice-287g'))
con<-dp_connect('ice-287g',quiet=TRUE)
tryCatch({
  dbExecute(con,"SET memory_limit='128MiB'")
  dbExecute(con,'SET threads=1')
  dbExecute(con,"SET max_temp_directory_size='0B'")
  stopifnot(dbGetQuery(con,'SELECT count(*) n FROM agreements')$n==3201)
  stopifnot(dbGetQuery(con,'SELECT count(*) n FROM agencies')$n==2491)
  stopifnot(nrow(dp_describe(con))==2,nrow(dp_describe(con,table='agreements'))==42)
  stopifnot(dbGetQuery(con,"SELECT count(*) n FROM agreements WHERE ST_AsText(ST_GeomFromWKB(geometry_wkb)) LIKE '%EMPTY'")$n==406)
  stopifnot(dbGetQuery(con,"SELECT count(*) n FROM agreements WHERE state_fips LIKE '0%'")$n>0)
  stopifnot(is.raw(dbGetQuery(con,'SELECT geometry_wkb FROM agreements LIMIT 1')$geometry_wkb[[1]]))
  example<-dbGetQuery(con,'SELECT status,count(*) AS agreements FROM agreements GROUP BY status ORDER BY status')
  stopifnot(identical(example$status,c('Active','Removed','Superseded')),all(as.numeric(example$agreements)==c(2725,273,203)))
  cat(jsonlite::toJSON(list(passed=TRUE,client='R datapond',version=as.character(packageVersion('datapond')),duckdb=as.character(packageVersion('duckdb')),example=example),auto_unbox=TRUE))
},finally=dp_disconnect(con))
